        public static string GetName(string locationId)
        {
            return Lookup(Names, locationId);
        }

        public static string GetRegion(string locationId)
        {
            return Lookup(Regions, locationId);
        }

        public static string GetArea(string locationId, int layer, int group)
        {
            return layer < 0 || group < 0 ? string.Empty : Lookup(Areas, locationId + "|" + layer.ToString(CultureInfo.InvariantCulture) + "|" + group.ToString(CultureInfo.InvariantCulture));
        }

        public static string GetLayer(string locationId, int layer)
        {
            return layer < 0 ? string.Empty : Lookup(Layers, locationId + "|" + layer.ToString(CultureInfo.InvariantCulture));
        }

        public static string GetLocation(string locationId, int layer = -1, int group = -1)
        {
            string region = GetRegion(locationId), map = GetName(locationId), area = GetArea(locationId, layer, group);
            return Join(Join(region, map), area);
        }

        private static string Join(string first, string second)
        {
            return string.IsNullOrEmpty(second) || first == second ? first : string.IsNullOrEmpty(first) ? second : first + " / " + second;
        }

        private static string Lookup(Dictionary<string, string> values, string key)
        {
            return key != null && values.TryGetValue(key, out var value) ? value : string.Empty;
        }
