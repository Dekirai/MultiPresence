        public static string GetMap(string section, string floor)
        {
            var area = GetMapArea(floor);
            if (area.Length == 0)
            {
                return string.Empty;
            }

            var room = section.StartsWith(floor + "_", StringComparison.Ordinal) ? GetMapRoom(section) : string.Empty;
            return room.Length == 0 ? area : area + " / " + room;
        }

        public static string GetMapArea(string floor)
        {
            return MapAreas.GetValueOrDefault(floor) ?? string.Empty;
        }

