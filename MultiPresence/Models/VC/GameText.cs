        public static string GetRegion(string? dungeonId)
        {
            return dungeonId != null && Regions.TryGetValue(dungeonId, out var name) ? name : "";
        }

        private static string Get(Dictionary<string, string> values, string? id)
        {
            return id != null && values.TryGetValue(id, out var name) ? name : id ?? "";
