        public static int ResolveMapId(int mapId, int areaId = 0)
        {
            return SceneAreas.TryGetValue(mapId.ToString(CultureInfo.InvariantCulture) + "|" + areaId.ToString(CultureInfo.InvariantCulture), out var id) ? id : mapId;
        }

        public static string GetRegion(int locationId)
        {
            return Regions.GetValueOrDefault(locationId) ?? string.Empty;
        }

        public static string GetMapRegion(int mapId)
        {
            return MapRegions.GetValueOrDefault(mapId) ?? string.Empty;
        }

        public static string GetRegion(int locationId, int mapId, int areaId = 0)
        {
            var name = GetMapRegion(ResolveMapId(mapId, areaId));
            return name.Length != 0 ? name : GetRegion(locationId);
        }

        public static string GetRoom(int mapId)
        {
            return Rooms.GetValueOrDefault(mapId) ?? string.Empty;
        }

        public static string GetRoom(int mapId, int areaId)
        {
            return GetRoom(ResolveMapId(mapId, areaId));
        }

        public static string GetLocation(int locationId, int mapId, int areaId = 0)
        {
            string region = GetRegion(locationId, mapId, areaId), room = GetRoom(mapId, areaId);
            return room.Length == 0 || room == region ? region : region.Length == 0 ? room : region + " / " + room;
        }
