        public static string GetLocation(Guid messageId)
        {
            return GameText.Get(messageId).Replace(" - ", " / ");
        }

        public static string GetRegion(Guid messageId)
        {
            var text = GameText.Get(messageId);
            var split = text.IndexOf(" - ", StringComparison.Ordinal);
            return split < 0 ? text : text.Substring(0, split);
        }

        public static string GetRoom(Guid messageId)
        {
            var text = GameText.Get(messageId);
            var split = text.IndexOf(" - ", StringComparison.Ordinal);
            return split < 0 ? string.Empty : text.Substring(split + 3);
        }
