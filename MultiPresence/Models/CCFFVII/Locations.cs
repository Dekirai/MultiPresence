        public static string GetName(int textId)
        {
            return Names.TryGetValue(textId, out var name) ? name : string.Empty;
        }

        public static string GetName(string textId)
        {
            return textId != null && textId.StartsWith("map_", StringComparison.Ordinal) && int.TryParse(textId.AsSpan(4), NumberStyles.None, CultureInfo.InvariantCulture, out int id) ? GetName(id) : string.Empty;
        }

        public static string GetLocation(int textId)
        {
            return GetName(textId).Replace(" – ", " / ");
        }

        public static string GetRegion(int textId)
        {
            string name = GetName(textId);
            int separator = name.IndexOf(" – ", StringComparison.Ordinal);
            return separator >= 0 ? name.Substring(0, separator) : name;
        }

        public static string GetArea(int textId)
        {
            string name = GetName(textId);
            int separator = name.IndexOf(" – ", StringComparison.Ordinal);
            return separator >= 0 ? name.Substring(separator + 3) : string.Empty;
        }

        public static string GetMapKey(int mapId)
        {
            return MapKeys.TryGetValue(mapId, out var key) ? key : string.Empty;
        }
