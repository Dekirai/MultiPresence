        public static string GetTitle(int missionId)
        {
            return Titles.TryGetValue(missionId, out var title) ? title : string.Empty;
        }

        public static string GetNumber(int missionId)
        {
            string title = GetTitle(missionId);
            int separator = title.IndexOf(':');
            return separator > 0 ? title.Substring(0, separator) : string.Empty;
        }

        public static string GetName(int missionId)
        {
            string title = GetTitle(missionId);
            int separator = title.IndexOf(':');
            return separator > 0 ? title.Substring(separator + 2) : string.Empty;
        }
